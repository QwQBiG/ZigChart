export const messages: Record<Locale, Record<MessageKey, string>> = { en: english, 'zh-CN': chinese };
let locale: Locale = 'en';

export function getLocale(): Locale { return locale; }
export function setLocale(next: Locale): void { locale = next; }

export function chooseLocale(saved: string | null, languages: readonly string[]): Locale {
  if (saved === 'en' || saved === 'zh-CN') return saved;
  for (const language of languages) {
    const prefix = language.toLowerCase().split('-')[0];
    if (prefix === 'en') return 'en';
    if (prefix === 'zh') return 'zh-CN';
  }
  return 'en';
}

export function t(key: MessageKey, params: Record<string, string | number> = {}): string {
  return messages[locale][key].replace(/\{(\w+)\}/g, (token, name: string) =>
    Object.hasOwn(params, name) ? String(params[name]) : token);
}

export function translateDocument(doc: Document): void {
  const attributes = ['data-i18n', 'data-i18n-title', 'data-i18n-aria-label'] as const;
  for (const attribute of attributes) {
    for (const node of doc.querySelectorAll<HTMLElement>(`[${attribute}]`)) {
      const key = node.getAttribute(attribute);
      if (!key || !Object.hasOwn(english, key)) continue;
      const value = t(key as MessageKey);
      if (attribute === 'data-i18n') node.textContent = value;
      else node.setAttribute(attribute.slice('data-i18n-'.length), value);
    }
  }
  doc.documentElement.lang = locale;
  doc.title = t('title');
  doc.querySelector<HTMLMetaElement>('meta[name="description"]')?.setAttribute('content', t('description'));
  const select = doc.querySelector<HTMLSelectElement>('#language-select');
  if (select) select.value = locale;
}
